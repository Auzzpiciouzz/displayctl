"""Durable Keep: turn a kept layout into Hyprland rules in our own monitors.lua.

Design: docs/hyprland-persistence.md, "Durable Keep". In short:
  - protocol changes are a preview; on Keep the layout is written as rules
    to ~/.config/hypr/displayctl/monitors.lua (loaded by the user's
    `pcall(dofile, ...)` line at the end of hyprland.lua);
  - a laptop panel is never disabled unconditionally: only while a monitor
    the layout was kept with is connected and on (checked at load time and
    again whenever an external monitor comes or goes);
  - files are written atomically, with a .prev copy for Undo.

Nothing here talks to Hyprland or Wayland; the caller reloads and verifies.
"""

import datetime
import json
import os

#!/usr/bin/env python3
"""List every display output the compositor knows about.

READ-ONLY: this only listens to what the compositor tells us. It never
creates a configuration, so it cannot change your displays.

Protocol: wlr-output-management-unstable-v1
  zwlr_output_manager_v1  - the global we bind; announces heads
  zwlr_output_head_v1     - one per physical output (even disabled ones)
  zwlr_output_mode_v1     - one per mode a head supports

Usage:
  list_outputs.py           print the outputs
  list_outputs.py --debug   also trace every raw Wayland message to stderr
"""

import argparse
import os

from pywayland.client import Display

# Generated by ./generate_protocols.sh from the protocol XML.
from protocols.wlr_output_management_unstable_v1 import ZwlrOutputManagerV1

# wl_output.transform enum values -> readable names.
TRANSFORMS = {
    0: "normal", 1: "90", 2: "180", 3: "270",
    4: "flipped", 5: "flipped-90", 6: "flipped-180", 7: "flipped-270",
}


class Mode:
    """Plain data holder that the zwlr_output_mode_v1 events fill in."""

    def __init__(self):
        self.width = 0
        self.height = 0
        self.refresh_mhz = 0  # the protocol sends refresh in milli-Hertz
        self.preferred = False

    def __str__(self):
        hz = self.refresh_mhz / 1000
        pref = "  (preferred)" if self.preferred else ""
        return f"{self.width}x{self.height} @ {hz:.3f} Hz{pref}"


class Head:
    """Plain data holder that the zwlr_output_head_v1 events fill in."""

    def __init__(self):
        self.name = ""
        self.description = ""
        self.make = ""
        self.model = ""
        self.serial = ""
        self.physical_size = (0, 0)  # millimetres
        self.enabled = False
        self.position = (0, 0)
        self.transform = 0
        self.scale = 1.0
        self.modes = []  # list of Mode, in the order the compositor sent them
        self.current_mode = None  # one of self.modes, or None if disabled


class OutputLister:
    def __init__(self):
        self.manager = None  # the bound zwlr_output_manager_v1 proxy
        self.heads = []
        self.done = False  # set once the manager sends its first 'done'

        # Proxies (Python objects for Wayland objects) -> our data holders.
        # The 'current_mode' event hands us a mode proxy, and this lets us
        # find which Mode it refers to.
        self._mode_data = {}

    # --- Registry: find the global we want ---------------------------------

    def on_global(self, registry, name, interface, version):
        """Called once for every global the compositor advertises."""
        if interface == ZwlrOutputManagerV1.name:
            # bind() creates our client-side object for that global. We ask
            # for at most the version our generated bindings understand.
            bind_version = min(version, ZwlrOutputManagerV1.version)
            self.manager = registry.bind(name, ZwlrOutputManagerV1, bind_version)
            self.manager.dispatcher["head"] = self.on_head
            self.manager.dispatcher["done"] = self.on_done

    # --- Manager events -----------------------------------------------------

    def on_head(self, manager, head_proxy):
        """A new head exists. Its properties arrive as separate events."""
        head = Head()
        self.heads.append(head)

        # Each handler below updates this head. The lambdas capture 'head'
        # so every proxy writes into its own data holder.
        d = head_proxy.dispatcher
        d["name"] = lambda _, v: setattr(head, "name", v)
        d["description"] = lambda _, v: setattr(head, "description", v)
        d["make"] = lambda _, v: setattr(head, "make", v)
        d["model"] = lambda _, v: setattr(head, "model", v)
        d["serial_number"] = lambda _, v: setattr(head, "serial", v)
        d["physical_size"] = lambda _, w, h: setattr(head, "physical_size", (w, h))
        d["enabled"] = lambda _, v: setattr(head, "enabled", bool(v))
        d["position"] = lambda _, x, y: setattr(head, "position", (x, y))
        d["transform"] = lambda _, v: setattr(head, "transform", v)
        d["scale"] = lambda _, v: setattr(head, "scale", v)
        d["mode"] = lambda _, mode_proxy: self.on_mode(head, mode_proxy)
        d["current_mode"] = lambda _, mode_proxy: setattr(
            head, "current_mode", self._mode_data.get(mode_proxy)
        )

    def on_mode(self, head, mode_proxy):
        """The head supports a new mode. Its details arrive as more events."""
        mode = Mode()
        head.modes.append(mode)
        self._mode_data[mode_proxy] = mode

        # A real function rather than a lambda: event handlers are called
        # from C, and must return None (a lambda here would return a tuple).
        def on_size(_, width, height):
            mode.width = width
            mode.height = height

        d = mode_proxy.dispatcher
        d["size"] = on_size
        d["refresh"] = lambda _, r: setattr(mode, "refresh_mhz", r)
        d["preferred"] = lambda _: setattr(mode, "preferred", True)

    def on_done(self, manager, serial):
        """Sent after a batch of head/mode events: the state is now consistent."""
        self.done = True

    # --- Main --------------------------------------------------------------

    def run(self):
        display = Display()  # uses $WAYLAND_DISPLAY
        display.connect()
        try:
            registry = display.get_registry()
            registry.dispatcher["global"] = self.on_global

            # roundtrip() sends our requests, then blocks until the
            # compositor has handled them and sent back every resulting event.
            # This first one delivers the list of globals.
            display.roundtrip()

            if self.manager is None:
                raise SystemExit(
                    "Compositor does not support zwlr_output_manager_v1"
                )

            # Binding the manager makes the compositor send every head, mode
            # and property, finishing with 'done'. Keep going until it arrives.
            while not self.done:
                display.roundtrip()
        finally:
            display.disconnect()

    def print_report(self):
        for head in self.heads:
            print(f"=== {head.name} ===")
            print(f"  description : {head.description}")
            print(f"  make        : {head.make}")
            print(f"  model       : {head.model}")
            print(f"  serial      : {head.serial or '(none)'}")
            w_mm, h_mm = head.physical_size
            print(f"  physical    : {w_mm} x {h_mm} mm")
            print(f"  enabled     : {head.enabled}")
            if head.enabled:
                print(f"  current mode: {head.current_mode}")
                print(f"  position    : {head.position[0]},{head.position[1]}")
                print(f"  scale       : {head.scale:g}")
                print(f"  transform   : {TRANSFORMS.get(head.transform, head.transform)}")
            print(f"  modes ({len(head.modes)}):")
            for mode in head.modes:
                marker = "*" if mode is head.current_mode else " "
                print(f"    {marker} {mode}")
            print()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="List Wayland outputs (read-only).")
    parser.add_argument(
        "--debug", action="store_true",
        help="trace every raw Wayland request and event to stderr",
    )
    args = parser.parse_args()

    if args.debug:
        # libwayland (the C library under pywayland) has a built-in tracer.
        # It checks this variable when the connection is opened, so it must
        # be set before Display.connect() runs. Each line is one message:
        #   " -> obj@id.request(args)"  = we sent a request
        #   "obj@id.event(args)"        = we received an event
        os.environ["WAYLAND_DEBUG"] = "1"

    lister = OutputLister()
    lister.run()
    lister.print_report()
